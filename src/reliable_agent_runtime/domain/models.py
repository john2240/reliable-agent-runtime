_IDENTIFIER_PATTERN: Final[re.Pattern[str]] = re.compile(r"^[a-z][a-z0-9_.-]{0,63}$")


@dataclass(frozen=True, slots=True)
class ToolSpec:
    """Static metadata used by policy, retries, and API discovery."""

    name: str
    description: str
    effect: ToolEffect = ToolEffect.READ
    version: str = "1.0.0"
    idempotent: bool = True
    requires_approval: bool = False
    timeout_seconds: float = 10.0
    max_attempts: int = 3
    backoff_seconds: float = 0.25
    tags: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if not _IDENTIFIER_PATTERN.fullmatch(self.name):
            raise ValueError(
                "tool name must match ^[a-z][a-z0-9_.-]{0,63}$",
            )
        if not self.description.strip():
            raise ValueError("tool description must not be blank")
        if self.timeout_seconds <= 0:
            raise ValueError("tool timeout_seconds must be positive")
        if self.max_attempts < 1:
            raise ValueError("tool max_attempts must be at least 1")
        if self.backoff_seconds < 0:
            raise ValueError("tool backoff_seconds must not be negative")


@dataclass(frozen=True, slots=True)
class PlanStep:
    """A declarative tool invocation generated by a planner or workflow."""

    id: str
    tool_name: str
    arguments: JsonObject
    depends_on: tuple[str, ...] = ()
    description: str | None = None

    def __post_init__(self) -> None:
        # Planner-owned dictionaries must not remain aliased with the persisted
        # plan. A caller mutating its request object after construction must not
        # silently change an in-flight run.
        object.__setattr__(self, "arguments", deepcopy(self.arguments))
        object.__setattr__(self, "depends_on", tuple(self.depends_on))
        if not _IDENTIFIER_PATTERN.fullmatch(self.id):
            raise PlanValidationError(
                f"invalid step id: {self.id!r}",
                details={"step_id": self.id},
            )
        if not _IDENTIFIER_PATTERN.fullmatch(self.tool_name):
            raise PlanValidationError(
                f"invalid tool name: {self.tool_name!r}",
                details={"tool_name": self.tool_name},
            )
        if self.id in self.depends_on:
            raise PlanValidationError(
                f"step {self.id!r} cannot depend on itself",
                details={"step_id": self.id},
            )


@dataclass(frozen=True, slots=True)
class ExecutionPlan:
    """Validated directed acyclic graph of tool calls."""

    id: str
    name: str
    steps: tuple[PlanStep, ...]
    compensate_on_failure: bool = True

    def __post_init__(self) -> None:
        object.__setattr__(self, "steps", tuple(self.steps))
        if not _IDENTIFIER_PATTERN.fullmatch(self.id):
            raise PlanValidationError(
                f"invalid plan id: {self.id!r}",
                details={"plan_id": self.id},
            )
        if not self.name.strip():
            raise PlanValidationError("plan name must not be blank")
        if not self.steps:
            raise PlanValidationError("plan must contain at least one step")
        if len(self.steps) > 100:
            raise PlanValidationError("plan cannot contain more than 100 steps")

        step_ids = [step.id for step in self.steps]
        if len(step_ids) != len(set(step_ids)):
            raise PlanValidationError("plan step ids must be unique")

        known_ids = set(step_ids)
        for step in self.steps:
            missing = set(step.depends_on) - known_ids
            if missing:
                raise PlanValidationError(
                    f"step {step.id!r} depends on unknown steps",
                    details={"step_id": step.id, "missing_dependencies": sorted(missing)},
                )

        self.topological_steps()

    def topological_steps(self) -> tuple[PlanStep, ...]:
        """Return a stable topological order and reject dependency cycles."""

        by_id = {step.id: step for step in self.steps}
        source_order = {step.id: index for index, step in enumerate(self.steps)}
        indegree = {step.id: len(step.depends_on) for step in self.steps}
        dependents: dict[str, list[str]] = {step.id: [] for step in self.steps}

        for step in self.steps:
            for dependency in step.depends_on:
                dependents[dependency].append(step.id)

        ready = sorted(
            (step_id for step_id, degree in indegree.items() if degree == 0),
            key=source_order.__getitem__,
        )
        ordered: list[PlanStep] = []

        while ready:
            current = ready.pop(0)
            ordered.append(by_id[current])
            for dependent in sorted(dependents[current], key=source_order.__getitem__):
                indegree[dependent] -= 1
                if indegree[dependent] == 0:
                    ready.append(dependent)
                    ready.sort(key=source_order.__getitem__)

        if len(ordered) != len(self.steps):
            cyclic = sorted(step_id for step_id, degree in indegree.items() if degree > 0)
            raise PlanValidationError(
                "plan dependencies contain a cycle",
                details={"cyclic_steps": cyclic},
            )

        return tuple(ordered)

    def terminal_steps(self) -> tuple[PlanStep, ...]:
        """Return sink steps whose outputs form the successful run result."""

        depended_on = {
            dependency
            for step in self.steps
            for dependency in step.depends_on
        }
        return tuple(
            step for step in self.topological_steps() if step.id not in depended_on
        )


@dataclass(frozen=True, slots=True)
class ErrorInfo:
    """Serializable failure data persisted with a run or step."""

    code: str
    message: str
    retryable: bool = False
    details: JsonObject = field(default_factory=dict)


@dataclass(slots=True)
class StepState:
    """Mutable execution state for one plan step."""

    status: StepStatus = StepStatus.PENDING
    attempts: int = 0
    call_id: str | None = None
    idempotency_key: str | None = None
    resolved_arguments: JsonObject | None = None
    output: JsonObject | None = None
    output_metadata: JsonObject = field(default_factory=dict)
    error: ErrorInfo | None = None
    approval_id: str | None = None
    started_at: datetime | None = None
    completed_at: datetime | None = None


@dataclass(slots=True)
class AgentRun:
    """Aggregate root for a reliable agent run."""

    id: str
    objective: str
    plan: ExecutionPlan
    input: JsonObject
    actor: str
    request_fingerprint: str
    status: RunStatus
    step_states: dict[str, StepState]
    version: int
    created_at: datetime
    updated_at: datetime
    result: JsonObject | None = None
    error: ErrorInfo | None = None

    @classmethod
    def create(
        cls,
        *,
        run_id: str,
        objective: str,
        plan: ExecutionPlan,
        input_data: JsonObject,
        actor: str,
        request_fingerprint: str,
        now: datetime | None = None,
    ) -> AgentRun:
        timestamp = now or datetime.now(tz=UTC)
        return cls(
            id=run_id,
            objective=objective,
            plan=plan,
            input=deepcopy(input_data),
            actor=actor,
            request_fingerprint=request_fingerprint,
            status=RunStatus.PENDING,
            step_states={step.id: StepState() for step in plan.steps},
            version=1,
            created_at=timestamp,
            updated_at=timestamp,
        )


@dataclass(frozen=True, slots=True)
class ToolContext:
    """Request-scoped metadata passed to every tool adapter."""

    run_id: str
    step_id: str
    call_id: str
    idempotency_key: str
    actor: str
    objective: str
    metadata: JsonObject = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class CheckResult:
    """Result of a tool precondition check."""

    passed: bool
    reason: str | None = None
    retryable: bool = False
    details: JsonObject = field(default_factory=dict)

    @classmethod
    def success(cls) -> CheckResult:
        return cls(passed=True)


@dataclass(frozen=True, slots=True)
class ToolResult:
    """Normalized output returned by a tool adapter."""

    output: JsonObject
    metadata: JsonObject = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class VerificationResult:
    """Tri-state verification used after normal or ambiguous execution."""

    outcome: VerificationOutcome
    details: str
    observed_output: JsonObject | None = None

    @classmethod
    def confirmed(
        cls,
        *,
        details: str = "postcondition verified",
        observed_output: JsonObject | None = None,
    ) -> VerificationResult:
        return cls(
            outcome=VerificationOutcome.CONFIRMED_SUCCESS,
            details=details,
            observed_output=observed_output,
        )


@dataclass(slots=True)
class Approval:
    """Human decision required before a sensitive step may execute."""

    id: str
    run_id: str
    step_id: str
    tool_name: str
    call_id: str
    reason: str
    arguments: JsonObject
    status: ApprovalStatus
    requested_at: datetime
    decided_at: datetime | None = None
    decided_by: str | None = None
    decision_reason: str | None = None


@dataclass(frozen=True, slots=True)
class RuntimeEvent:
    """Append-only audit record."""

    id: str
    run_id: str
    event_type: EventType
    created_at: datetime
    payload: JsonObject = field(default_factory=dict)
    step_id: str | None = None
    sequence: int | None = None
